// Durchbruch prüfen: Signatur → Tor instand setzen → Späher hindurch → Erstsichtung (Enthüllung) → Forschungsakte.
// node scripts/discovery-shot.mjs <outdir>
import { chromium } from 'playwright';
import { launchOpts } from './browser.mjs';
import { distUrl } from './serve.mjs';
const out = process.argv[2];
const browser = await chromium.launch(launchOpts());
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const errors = [];
const fail = (m) => errors.push(m);
page.on('pageerror', (e) => errors.push(String(e)));
await page.goto(await distUrl());
await page.click('text=Loslegen mit Bergbau');
await page.waitForTimeout(2200);
await page.evaluate(() => { const g = window.__game; g.state.help = { coachOff: true }; g.state.credits = 5e6; g.state.frontier = { signatures: ['rhy>f-ausblick'], discovered: [] }; g.refresh(); });
await page.click('#nav [data-act="nav"][data-tab="map"]');
await page.waitForTimeout(900);
await page.evaluate(() => { const g = window.__game; g.ui.galaxySel = 'rhy'; g.refresh(); });
await page.waitForTimeout(300);
await page.click('.gx-card [data-act="scout-buy"]');
await page.waitForTimeout(200);
await page.screenshot({ path: `${out}/durchbruch-1-signatur.png` });
await page.click('.gx-card [data-act="gate-repair"]');
await page.waitForTimeout(200);
// Baustelle: Waren aus dem eigenen Lager liefern, den Rest zukaufen
await page.evaluate(() => { const g = window.__game; const st = g.state.stations[0]; st.inventory.hullparts = 400; st.inventory.energycells = 600; g.refresh(); });
await page.waitForTimeout(200);
if (!(await page.locator('.gx-card .gx-gate.site').count())) fail('Keine Baustelle am Tor');
await page.click('.gx-card [data-act="gate-deliver"]');
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/durchbruch-1b-baustelle.png` });
const left = await page.evaluate(() => window.__game.state.stations[0].inventory.hullparts ?? 0);
if (left !== 150) fail('Lieferung nimmt falsche Menge: ' + left);
await page.click('.gx-card [data-act="gate-buy"]');
await page.waitForTimeout(200);
await page.evaluate(() => { const g = window.__game; g.step(35 * 60); g.refresh(); });
await page.waitForTimeout(500);
if (!(await page.locator('.gx-card [data-act="gate-through"]').count())) fail('Tor nach Instandsetzung nicht offen');
await page.screenshot({ path: `${out}/durchbruch-2-offen.png` });
await page.click('.gx-card [data-act="gate-through"]');
await page.waitForTimeout(200);
await page.evaluate(() => { const g = window.__game; g.step(45 * 60); g.refresh(); });
await page.waitForTimeout(600);
if (!(await page.locator('#reveal').count())) fail('Keine Erstsichtung');
await page.waitForTimeout(3600);
await page.screenshot({ path: `${out}/durchbruch-3-erstsichtung.png` });
await page.click('#reveal [data-rv="akte"]');
await page.waitForTimeout(800);
if (!(await page.locator('#modal .akte-item:not(.unknown)').count())) fail('Akte ohne Eintrag');
await page.screenshot({ path: `${out}/durchbruch-4-akte.png` });
const disc = await page.evaluate(() => window.__game.state.frontier.discovered);
if (!disc.includes('f-ausblick')) fail('Sektor nicht entdeckt');
await page.evaluate(() => { const g = window.__game; g.ui.modal = null; g.ui.galaxySel = null; g.refresh(); });
await page.waitForTimeout(600);
await page.screenshot({ path: `${out}/durchbruch-5-karte.png` });
// Der neue Sektor ist spielbar: Karte zeigt „Hinfliegen“, die Sektoransicht öffnet sich
await page.evaluate(() => { const g = window.__game; g.ui.galaxySel = 'f-ausblick'; g.refresh(); });
await page.waitForTimeout(400);
if (!(await page.locator('.gx-card [data-act="goto-sector"]').count())) fail('Neuer Sektor nicht anfliegbar');
await page.screenshot({ path: `${out}/durchbruch-6-karte-spielbar.png` });
await page.click('.gx-card [data-act="goto-sector"]');
await page.waitForTimeout(1500);
const sec = await page.evaluate(() => window.__game.ui.sector);
if (sec !== 'f-ausblick') fail('Sektoransicht nicht geöffnet: ' + sec);
await page.screenshot({ path: `${out}/durchbruch-7-sektor.png` });
await browser.close();
console.log(JSON.stringify({ errors }, null, 1));
if (errors.length) process.exit(1);

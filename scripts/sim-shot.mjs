// Bildschirmfotos des Simulators: Übersicht (Arbeit, Kampf), Spielseite, Einsatzseite
import { chromium } from 'playwright';
import { launchOpts } from './browser.mjs';
import { distUrl } from './serve.mjs';
import { simTab } from './simNav.mjs';
const out = process.argv[2] ?? 'shots';
const browser = await chromium.launch(launchOpts());
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, hasTouch: true, isMobile: true });
page.on('pageerror', (e) => console.log('FEHLER', e.message));
await page.goto(await distUrl());
await page.click('text=Loslegen mit Bergbau');
await page.waitForTimeout(1000);
await page.evaluate(() => { const g = window.__game; g.state.help = { coachOff: true }; document.getElementById('reveal')?.remove(); g.ui.modal = { type: 'minigames' }; g.refresh(); });
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/sim-arbeit.png` });
await page.screenshot({ path: `${out}/sim-arbeit-lang.png`, fullPage: true });
await simTab(page, 'combat');
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/sim-kampf.png` });
await page.evaluate(() => { document.querySelector('#modal .sheet-body').scrollTop = 520; });
await page.waitForTimeout(200);
await page.screenshot({ path: `${out}/sim-kampf-2.png` });
await simTab(page, 'work');
await page.click('#modal [data-act="mg-game"][data-kind="pipes"]');
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/sim-seite.png` });
await page.evaluate(() => { document.querySelector('#modal .sheet-body').scrollTop = 600; });
await page.screenshot({ path: `${out}/sim-seite-2.png` });
await page.click('#modal [data-act="mg-home"]');
await simTab(page, 'combat');
await page.click('#modal [data-act="mg-game"][data-mission="konvoi"]');
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/sim-einsatz.png` });
await browser.close();
